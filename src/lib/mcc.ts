/** MCCs that many Indian credit cards exclude from reward points / cashback. */
const OFTEN_EXCLUDED = new Set([
  '4900', '5172', '5541', '5542', '5552', '5983', '6010', '6011', '6012', '6050', '6051', '6211', '6300',
  '6513', '6529', '6530', '6540', '7995', '8211', '8220', '8241', '8244', '8249', '8299', '9211', '9222',
  '9223', '9311', '9399', '9402', '9405', '4829', '5960', '5944',
]);

export function lookupMcc(code: string): MccInfo | null {
  const c = code.trim().padStart(4, '0');
  const hit = T[c];
  if (hit) return { desc: hit[0], group: hit[1] };
  const n = Number(c);
  if (n >= 3000 && n <= 3299) return { desc: 'Airline (brand-specific code)', group: 'Travel' };
  if (n >= 3351 && n <= 3500) return { desc: 'Car Rental (brand-specific code)', group: 'Travel' };
  if (n >= 3501 && n <= 3999) return { desc: 'Hotel / Lodging (brand-specific code)', group: 'Travel' };
  if (c === '0000') return { desc: 'Person-to-person (no merchant category)', group: 'Transfers' };
  return null;
}

export const isOftenExcluded = (code: string) => OFTEN_EXCLUDED.has(code.trim().padStart(4, '0'));

/** Map an MCC group onto one of the app's spend categories. */
export function categoryForMcc(code: string): string | undefined {
  const g = lookupMcc(code)?.group;
  const map: Record<string, string> = {
    Food: 'Food & Dining',
    Groceries: 'Groceries',
    Shopping: 'Shopping',
    Travel: 'Travel',
    Fuel: 'Fuel',
    Bills: 'Bills & Utilities',
    Entertainment: 'Entertainment',
    Health: 'Health',
    Education: 'Education',
    Rent: 'Rent',
    Subscriptions: 'Subscriptions',
    'Personal Care': 'Personal Care',
    Transfers: 'Transfers',
    Financial: 'Transfers',
  };
  return g ? map[g] ?? 'Other' : undefined;
}
